#!/usr/bin/env python3
"""Build a reproducible, offline HTML from the maintained modules (Python stdlib only)."""
import argparse
import base64
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def data_uri(path, mime):
    return "data:" + mime + ";base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def build(entry="index.html"):
    entry = (ROOT / entry).resolve()
    if not entry.is_relative_to(ROOT):
        raise ValueError("Entry must be inside the repository")
    html = entry.read_text(encoding="utf-8")

    def stylesheet(match):
        path = ROOT / match[1]
        css = path.read_text(encoding="utf-8")
        def inline_url(m):
            ref = m[1].strip("'\"")
            if ref.startswith(("data:", "#")):
                return m[0]
            asset = (path.parent / ref).resolve()
            if not asset.is_relative_to(ROOT):
                raise ValueError("Asset outside repository: " + ref)
            if asset.suffix != ".woff2":
                raise ValueError("Unsupported CSS asset: " + ref)
            return 'url("' + data_uri(asset, "font/woff2") + '")'
        css = re.sub(r"url\(([^)]+)\)", inline_url, css)
        return "<style>\n/* Source: " + match[1] + " */\n" + css + "\n</style>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', stylesheet, html)
    payload = ""
    if 'js/ui/intro.js' in html:
        clips = {p.stem: data_uri(p, "video/webm") for p in sorted((ROOT / "assets/intro").glob("*.webm"))}
        payload = "<script>\nconst STANDALONE_CLIPS=" + json.dumps(clips, separators=(",", ":")) + ";\n</script>\n"
    html = html.replace('<script src=', payload + '<script src=', 1)

    def script(match):
        js = (ROOT / match[1]).read_text(encoding="utf-8")
        js = re.sub(r"</script", r"<\\/script", js, flags=re.I)
        return "<script>\n/* Source: " + match[1] + " */\n" + js + "\n</script>"
    html = re.sub(r'<script src="([^"]+)"></script>', script, html)
    licenses = "\n\n".join(p.name + "\n" + p.read_text(encoding="utf-8")
                           for p in sorted((ROOT / "assets/fonts").glob("OFL-*.txt")))
    notice = "<!-- Generated by tools/build.py. Edit repository index.html, css/ and js/.\n" + licenses.replace("--", "—") + "\n-->\n"
    return html.replace("<html ", notice + "<html ", 1).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the portable HTML differs from maintained sources")
    parser.add_argument("--entry", default="index.html", help="HTML entry to package (default: index.html)")
    parser.add_argument("--output", type=Path, help="Output path (defaults to dist/<entry-name>.html)")
    args = parser.parse_args()
    entry = (ROOT / args.entry).resolve()
    output = args.output.resolve() if args.output else ROOT / "dist" / ("starsea.html" if entry.name == "index.html" else entry.stem + ".html")
    if output == entry:
        raise SystemExit("Choose a different output path to keep the modular web entry.")
    result = build(args.entry)
    if args.check:
        if not output.exists() or output.read_bytes() != result:
            raise SystemExit("Generated HTML is out of date. Rebuild it from the selected entry.")
        print("Generated HTML matches source modules.")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_suffix(output.suffix + ".tmp")
    tmp.write_bytes(result)
    tmp.replace(output)
    print(f"Built {output.name}: {len(result):,} bytes (all referenced resources included).")


if __name__ == "__main__":
    main()
